import type { ResolvedColorScheme } from "./color-scheme-types";
import { composeTheme } from "./compose-theme";
import { cornerRules } from "./corners/corners";
import { BRAND_CODES, BRANDS, LEGAL_THEMES, themeAxisSelector } from "./theme-input";
import type { BrandCode, ThemeInput } from "./theme-input";
import { brandPointer } from "./tokens/brand-pointers";
import type { BrandPointer } from "./tokens/brand-pointers";
import { BRAND_RAMP_TOKEN_NAMES } from "./tokens/brand-ramps";
import { derivedRoleSources, LIGHT_RESET_KEYS, isDerivedTokenName, TOKEN_NAMES } from "./tokens/contract";
import type { TokenContract, TokenName } from "./tokens/contract";
import { DEFAULTS } from "./tokens/defaults";
import { derivedRoleCss } from "./tokens/derived-tokens";
import { PRIMITIVE_NAMES, PRIMITIVES } from "./tokens/primitives";
import { DARK_RESET_KEYS } from "./tokens/reset-keys";

const GENERATED_FILE_HEADER = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT DIRECTLY.
 *
 * Generated by the token pipeline. TypeScript theme modules are the source of truth.
 */

`;

function cssCustomProperty(name: string, value: string): string {
  return `  --${name}: ${value};`;
}

/**
 * The value a theme rule declares for one composed role. A mixed derived role declares its
 * live `color-mix()`, so the browser mixes the sources of the element that carries the rule.
 * Every other role declares its composed value. The catalog, the docs and design tools
 * read the composed literals.
 */
function cssValue(name: TokenName, value: string): string {
  return isDerivedTokenName(name) ? derivedRoleCss(name, value) : value;
}

function cssRule(
  selectors: readonly string[],
  declarations: readonly (readonly [string, string])[],
  colorScheme?: ResolvedColorScheme
): string {
  const body = declarations.map(([name, value]) => cssCustomProperty(name, value));
  if (colorScheme !== undefined) body.push(`  color-scheme: ${colorScheme};`);
  return `${selectors.join(",\n")} {\n${body.join("\n")}\n}`;
}

/**
 * A rule's selectors in one scheme. A light rule targets one selector. A dark rule lists the
 * direct and the descendant form in one selector list, so the emitter writes a palette body once,
 * not twice.
 */
function schemeSelectors(selector: string, colorScheme: ResolvedColorScheme): string[] {
  return colorScheme === "dark"
    ? [`[data-theme="dark"]${selector}`, `[data-theme="dark"] ${selector}`]
    : [selector];
}

/** A theme rule in one scheme, which also sets `color-scheme`. */
function themeRule(
  selector: string,
  declarations: readonly (readonly [string, string])[],
  colorScheme: ResolvedColorScheme
): string {
  return cssRule(schemeSelectors(selector, colorScheme), declarations, colorScheme);
}

function rootDeclarations(): (readonly [string, string])[] {
  const primitives = PRIMITIVE_NAMES.map((name) => [name, PRIMITIVES[name]] as const);
  const roles = TOKEN_NAMES.map((name) => [name, cssValue(name, DEFAULTS[name])] as const);
  return [...primitives, ...roles];
}

function emitRoot(): string {
  return cssRule([":root"], rootDeclarations());
}

const POINTER_KEYS: ReadonlySet<TokenName> = new Set([
  "brand",
  "brand-foreground",
] satisfies (keyof BrandPointer)[]);

/**
 * The derived roles that read the brand pointer. A host restyles a brand at the pointer's
 * weight, one attribute such as `.app[data-theme-brand="tkas"]`, so no rule declares these
 * roles at more than that weight. The brand pointer carries their neutral light values, and
 * no palette rule declares them: every branded and every dark palette rule leaves them to a
 * companion rule that puts its scheme and identity qualifiers in `:where()`.
 */
const BRAND_SCOPED_KEYS = TOKEN_NAMES.filter(
  (name) => isDerivedTokenName(name) && derivedRoleSources(name).some((source) => POINTER_KEYS.has(source))
);

function brandScopedDeclarations(tokens: TokenContract): (readonly [string, string])[] {
  return BRAND_SCOPED_KEYS.map((key) => [key, cssValue(key, tokens[key])] as const);
}

/**
 * The keys the brand rules and the companions declare: the pointer and the ramps, which
 * `emitBrandPointers` declares per brand and segment, and the brand-scoped roles. A palette rule
 * never declares them, so each keeps one override weight.
 */
const BRAND_RULE_KEYS: ReadonlySet<TokenName> = new Set<TokenName>([
  ...POINTER_KEYS,
  ...BRAND_RAMP_TOKEN_NAMES,
  ...BRAND_SCOPED_KEYS,
]);

/**
 * A full palette rule's declarations in one scheme, less `BRAND_RULE_KEYS`. A light segment rule
 * takes its keys from `changedKeys`, which leaves them out as well.
 *
 * Light layers declare `LIGHT_RESET_KEYS` only, so a host override of a role no palette sets, such
 * as `--popover` or `--chart-*`, inherits through the scope. Dark layers declare all of
 * `DARK_RESET_KEYS`, which is every key any light or dark palette can change except the light-only
 * keys. The light rule of the same element declares those in both schemes, so a host override of
 * one at the light rule's weight holds in dark.
 */
function paletteDeclarations(
  overrides: Partial<TokenContract>,
  colorScheme: ResolvedColorScheme
): (readonly [string, string])[] {
  const resetKeys = colorScheme === "dark" ? DARK_RESET_KEYS : LIGHT_RESET_KEYS;
  return resetKeys
    .filter((key) => !BRAND_RULE_KEYS.has(key))
    .map((key) => [key, cssValue(key, overrides[key] ?? DEFAULTS[key])] as const);
}

/**
 * The companion of a palette rule: the brand-scoped roles for one brand, with the scheme and
 * the palette's other qualifiers weighing nothing. It ties the brand pointer and follows it, so
 * it wins over the pointer's values. Every companion has that one weight, so the last one that
 * matches wins: the dark companions follow the light ones, and a segment's follows its base's.
 * A host override at the pointer's weight that comes later wins over all of them.
 */
function brandScopedRule(
  qualifiers: string,
  brand: BrandCode,
  tokens: TokenContract,
  colorScheme: ResolvedColorScheme
): string {
  const subject = themeAxisSelector("brand", brand);
  return cssRule(
    schemeSelectors(qualifiers, colorScheme).map((selector) => `:where(${selector})${subject}`),
    brandScopedDeclarations(tokens)
  );
}

/**
 * A brand's neutral theme in its first segment, the theme its brand rule describes. `LEGAL_THEMES`
 * lists each brand's segments in `BRANDS` order, so the first match is the first segment.
 */
function neutralTheme(brand: BrandCode): ThemeInput {
  const theme = LEGAL_THEMES.find(
    (candidate) => candidate.identity === "neutral" && candidate.brand === brand
  );
  if (theme === undefined) {
    throw new Error(`Brand ${brand} has no legal neutral theme`);
  }
  return theme;
}

/** A composed theme's ramp tokens as declarations, in token order. */
function rampDeclarations(tokens: TokenContract): (readonly [string, string])[] {
  return BRAND_RAMP_TOKEN_NAMES.map((name) => [name, tokens[name]] as const);
}

/**
 * The brand rules: the pointer, the roles that read it, and the brand's ramps. The ramps have one
 * value per brand and segment in both schemes and identities, so the brand rule declares them at
 * the brand's weight, and no identity or scheme rule declares them. A segment whose ramps differ
 * from the brand's first segment, such as Fjordkraft company with its teal hue, gets its own rule
 * with the segment attribute beside the brand. That rule outweighs the brand rule in both schemes.
 */
function emitBrandPointers(): string {
  const brandRules: string[] = [];
  const segmentRules: string[] = [];
  for (const code of BRAND_CODES) {
    const selector = themeAxisSelector("brand", code);
    const pointer = brandPointer(code);
    const baseTheme = neutralTheme(code);
    const base = composeTheme(baseTheme, "light");
    brandRules.push(
      cssRule(
        [selector],
        [
          ["brand", pointer.brand],
          ["brand-foreground", pointer["brand-foreground"]],
          ...brandScopedDeclarations(base),
          ...rampDeclarations(base),
        ]
      )
    );
    for (const theme of LEGAL_THEMES) {
      if (theme.identity !== "neutral" || theme.brand !== code || theme === baseTheme) {
        continue;
      }
      const tokens = composeTheme(theme, "light");
      if (BRAND_RAMP_TOKEN_NAMES.every((name) => tokens[name] === base[name])) {
        continue;
      }
      segmentRules.push(
        cssRule([`${selector}${themeAxisSelector("segment", theme.segment)}`], rampDeclarations(tokens))
      );
    }
  }
  return [...brandRules, ...segmentRules].join("\n\n");
}

function emitNeutralReset(): string {
  return themeRule(themeAxisSelector("identity", "neutral"), paletteDeclarations({}, "light"), "light");
}

/**
 * The neutral identity has one palette for every brand, so one composed neutral dark
 * theme names the dark scope's declarations. Its brand pointer is not part of
 * `THEME_RESET_KEYS`, so the choice of brand and segment does not matter.
 */
function neutralDarkTheme(): ThemeInput {
  return neutralTheme(BRAND_CODES[0]);
}

function emitNeutralDarkPalette(): string {
  const identity = themeAxisSelector("identity", "neutral");
  const palette = themeRule(
    identity,
    paletteDeclarations(composeTheme(neutralDarkTheme(), "dark"), "dark"),
    "dark"
  );
  // The shared palette is brand-agnostic, but the brand-scoped roles follow the brand.
  const brandScoped = BRAND_CODES.map((code) =>
    brandScopedRule(identity, code, composeTheme(neutralTheme(code), "dark"), "dark")
  );
  return [palette, ...brandScoped].join("\n\n");
}

/** The corner rules from `corners.ts`, formatted like every other rule. */
function emitCorners(): string {
  return cornerRules()
    .map((rule) => cssRule([rule.selector], rule.declarations))
    .join("\n\n");
}

/**
 * The roles a segment changes against its brand base, leaving out the keys the brand rules declare.
 * A derived role counts as changed wherever one of its sources does, because the rule must declare
 * its `color-mix()` again to mix the segment's sources instead of inheriting the base's result.
 */
function changedKeys(base: TokenContract, tokens: TokenContract): TokenName[] {
  const differs = (key: TokenName): boolean => tokens[key] !== base[key];
  return TOKEN_NAMES.filter(
    (key) =>
      !BRAND_RULE_KEYS.has(key) &&
      (isDerivedTokenName(key) ? derivedRoleSources(key).some(differs) : differs(key))
  );
}

/** Whether the two compositions differ in any token. */
function differsFrom(base: TokenContract, tokens: TokenContract): boolean {
  return changedKeys(base, tokens).length > 0;
}

/**
 * Emits each brand's rule from its composed base theme, then a segment rule wherever the segment
 * departs from that base. Light segment rules carry only the changed keys. Dark segment rules
 * declare the full dark reset set, like every other dark rule.
 *
 * A segment that departs only in light still gets a dark rule. The light segment selector
 * `[identity][brand][segment]` ties the dark brand selector `[dark][identity][brand]`. Without the
 * four-attribute dark segment rule, a dark scope would resolve that tie by emission order instead
 * of by specificity. The tie only covers the keys both rules declare. A light-only key is never in
 * a dark rule, so a light segment rule's value for one wins in dark by being the only declaration
 * at that weight, and the composed dark theme keeps it.
 */
function emitBrandPalettes(colorScheme: ResolvedColorScheme): string {
  const rules: string[] = [];
  for (const brand of BRAND_CODES) {
    const themes = LEGAL_THEMES.filter((theme) => theme.identity === "branded" && theme.brand === brand);
    // Resolve the base by the brand's first segment rather than `themes[0]`, so base
    // selection does not depend on `LEGAL_THEMES` ordering. Its rule carries no
    // `data-theme-segment`, so it is the fallback that an element without a segment, or
    // with a segment that has no sheet, resolves.
    const [baseSegment] = BRANDS[brand].segments;
    const baseTheme = themes.find((theme) => theme.segment === baseSegment);
    if (baseTheme === undefined) {
      throw new Error(`Brand ${brand} has no legal branded themes`);
    }
    const base = composeTheme(baseTheme, colorScheme);
    // The dark arm also asks whether the segment departs in light, so it needs the light
    // base beside the composed base it already holds.
    const lightBase = colorScheme === "dark" ? composeTheme(baseTheme, "light") : base;
    const identity = themeAxisSelector("identity", "branded");
    const selector = `${identity}${themeAxisSelector("brand", brand)}`;
    rules.push(
      themeRule(selector, paletteDeclarations(base, colorScheme), colorScheme),
      brandScopedRule(identity, brand, base, colorScheme)
    );
    for (const theme of themes.filter((candidate) => candidate !== baseTheme)) {
      const lightTokens = composeTheme(theme, "light");
      const lightDeparts = differsFrom(lightBase, lightTokens);
      const tokens = colorScheme === "light" ? lightTokens : composeTheme(theme, "dark");
      // A light-only departure still gets its dark rule, so the four-attribute dark
      // segment selector wins the tie with the light segment selector by specificity.
      const departs = colorScheme === "light" ? lightDeparts : lightDeparts || differsFrom(base, tokens);
      // tkas, guen, elma and ngfi have a company segment but no sheet, so they get no rule in
      // either scheme.
      if (!departs) continue;
      const segment = themeAxisSelector("segment", theme.segment);
      const declarations =
        colorScheme === "dark"
          ? paletteDeclarations(tokens, "dark")
          : changedKeys(base, tokens).map((key) => [key, cssValue(key, tokens[key])] as const);
      rules.push(
        themeRule(`${selector}${segment}`, declarations, colorScheme),
        // It follows the base companion at the same weight, so the segment's values win.
        brandScopedRule(`${identity}${segment}`, brand, tokens, colorScheme)
      );
    }
  }
  return rules.join("\n\n");
}

/**
 * Composes every theme as a guard, not a computation. `composeTheme` throws when a theme is missing
 * its must-override tokens, so generation fails on the same contract the theme tests assert.
 */
function assertAllThemesCompose(): void {
  for (const theme of LEGAL_THEMES) {
    composeTheme(theme);
    composeTheme(theme, "dark");
  }
}

export function generateThemesCss(): string {
  assertAllThemesCompose();

  return [
    GENERATED_FILE_HEADER.trimEnd(),
    emitRoot(),
    emitBrandPointers(),
    emitNeutralReset(),
    emitBrandPalettes("light"),
    emitCorners(),
    emitNeutralDarkPalette(),
    emitBrandPalettes("dark"),
    "",
  ].join("\n\n");
}
