/** Minutes after `iso`, as an ISO-comparable timestamp. */
function later(iso: string, minutes: number): string {
  return new Date(Date.parse(iso) + minutes * 60_000).toISOString();
}

/**
 * The activity log an order's status implies: what the sales tool and Core wrote on the way there.
 * Derived so every order's log agrees with its status and Elhub answer.
 */
function activityFor(seed: OrderSeed, elhub: ElhubCheck): readonly ActivityEvent[] {
  const event = (minutes: number, title: string, detail: string, author?: SellerId): ActivityEvent => ({
    id: `${String(seed.id)}-${String(minutes)}`,
    at: later(seed.created, minutes),
    title,
    detail,
    author,
  });
  const created = event(0, "Order created", `${seed.channel} · ${SELLERS[seed.seller].team}`, seed.seller);
  if (seed.status === "Ready") {
    return [event(0, "Draft saved", `${seed.product} for ${seed.customer}`, seed.seller)];
  }
  const sent = event(1, "Contract sent by SMS", "Signing link valid for 14 days");
  const log: ActivityEvent[] = [created, sent];
  switch (elhub._tag) {
    case "OwnerMismatch":
      log.push(event(2, "Elhub check failed", `Meter point is registered to ${elhub.registeredOwner}`));
      break;
    case "MeterPointNotFound":
      log.push(event(1, "Elhub check failed", "Elhub has no meter point with this ID"));
      break;
    case "Verified":
      log.push(event(2, "Elhub check passed", "Owner matches the customer"));
      break;
    case "NotChecked":
      break;
  }
  if (seed.status === "VerifyPersonFailed") {
    log.push(event(3, "Person verification failed", "The SSN did not match the National Registry"));
  }
  if (["AwaitingStartup", "InProgress", "Done"].includes(seed.status)) {
    log.push(event(180, "Customer approved the contract", "Signed with BankID"));
  }
  if (seed.status === "SendtToTm") {
    log.push(event(1440, "Sent to telemarketing", "No answer after two reminders", "mysil"));
  }
  if (seed.status === "Done") {
    log.push(event(4320, "Delivery started", `Startup confirmed by ${seed.gridOwner}`));
  }
  if (seed.status === "Cancelled") {
    log.push(event(600, "Order cancelled", "The customer used the right of withdrawal", seed.seller));
  }
  return log;
}

function elhubFor(seed: OrderSeed): ElhubCheck {
  if (seed.elhub !== undefined) {
    return seed.elhub;
  }
  return seed.status === "Ready"
    ? { _tag: "NotChecked" }
    : { _tag: "Verified", checkedAt: later(seed.created, 2) };
}

/** The 51 orders the window opens with. */
export const ORDERS: readonly Order[] = SEEDS.map((seed) => {
  const elhub = elhubFor(seed);
  const {
    priceArea,
    gridOwner,
    annualKwh,
    unread = false,
    elhub: _seeded,
    campaign,
    startup = "Change of supplier",
    salesType = "New sale",
    ...order
  } = seed;
  return {
    ...order,
    campaign,
    startup,
    salesType,
    facility: { _tag: "Known", priceArea, gridOwner, annualKwh },
    unread,
    elhub,
    activity: activityFor(seed, elhub),
  };
});
