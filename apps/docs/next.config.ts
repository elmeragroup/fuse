import createMdx from "@next/mdx";
import type { NextConfig } from "next";
import path from "node:path";
import { fileURLToPath } from "node:url";

const workspaceRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "../..");

/**
 * The e2e suite's build, `docs#build:e2e`, sets this to expose Next's Instant Navigation testing
 * API, which `@next/playwright`'s `instant()` drives. Only that task declares it, so strict env
 * mode keeps it out of `docs#build`, the task the container image runs.
 */
const testingApi = process.env.DOCS_TESTING_API === "1";

const nextConfig: NextConfig = {
  /**
   * `pnpm shots` serves this checkout with `next dev` beside `docs#test:e2e`, so Next, which has no
   * CLI flag or environment variable of its own for the output directory, reads one here. The
   * testing build writes to `.cache/next-e2e`, so `.next` stays the build the container ships and
   * the unit suite reads; `next start` with `DOCS_TESTING_API=1` serves the testing build.
   */
  // oxlint-disable-next-line turbo/no-undeclared-env-vars -- only `pnpm shots` sets it, outside turbo; strict env mode keeps it out of turbo builds
  distDir: process.env.DOCS_DIST_DIR ?? (testingApi ? ".cache/next-e2e" : ".next"),
  /**
   * The container image runs `node apps/docs/server.js` from `.next/standalone` (see
   * `Dockerfile`). Tracing from the workspace root keeps the linked workspace packages in
   * that bundle instead of leaving them behind as pnpm symlinks. The testing build skips the
   * bundle: `next start` serves it from its output directory, and nothing reads its standalone copy.
   */
  output: testingApi ? undefined : "standalone",
  outputFileTracingRoot: workspaceRoot,
  /**
   * The OG image routes read Roboto and the Elmera mark with `fs` at request time
   * (`src/og/og-assets.ts`). Tracing cannot follow a path built at runtime, so the files are
   * named here and the standalone bundle carries them.
   */
  outputFileTracingIncludes: {
    "/og/**": [
      "./node_modules/@fontsource/roboto/files/roboto-latin-{500,600}-normal.woff",
      // SIL OFL 1.1 requires the license text with every copy of the fonts.
      "./node_modules/@fontsource/roboto/LICENSE",
      "./public/landing/marks/elma.svg",
    ],
  },
  /** Component pages are authored as `page.mdx` route files. */
  pageExtensions: ["ts", "tsx", "mdx"],
  /**
   * `next dev` otherwise writes `AGENTS.md`/`CLAUDE.md` into this app on every start.
   * Agent instructions in this repo are authored, not generated by a dev server.
   */
  agentRules: false,
  /**
   * Every route prerenders what it can and streams only what reads the request. Each route group
   * prerenders whole (`ensureStatic` on its layout); the landing's `?theme=` address reaches a
   * prerendered page through `src/proxy.ts`'s rewrite, not a request read.
   */
  cacheComponents: true,
  /**
   * Links prefetch one App Shell per route and share it, instead of one prefetch per link. Next
   * logs a warning when Cache Components is on without it.
   */
  partialPrefetching: true,
  /** Responses do not advertise the framework. */
  poweredByHeader: false,
  /**
   * Hardening headers on every response. None needs a nonce, so they hold on prerendered routes:
   * no MIME sniffing, no full URL in the referrer to other origins, no framing by other origins,
   * no `<base>` from elsewhere and no plugins. A `script-src` policy waits on the hash-based CSP
   * decision recorded in the theming handbook.
   */
  headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Content-Security-Policy",
            value: "frame-ancestors 'self'; base-uri 'self'; object-src 'none'",
          },
        ],
      },
    ];
  },
  /**
   * The themed route is not an address of its own: a request for it goes to the shared address it
   * stands for, so search engines and visitors only meet `/?theme=`. Redirects run before
   * `src/proxy.ts`, so this leaves the proxy's rewrite alone.
   */
  redirects() {
    return [{ source: "/themed/:theme", destination: "/?theme=:theme", permanent: false }];
  },
  experimental: {
    /**
     * Serves `app/global-not-found.tsx` for an address no route matches. The app has a root layout
     * per route group, so no single layout can frame a `not-found.tsx` for every address.
     */
    globalNotFound: true,
    /** Drops unreachable work from Turbopack's memory and its persistent cache. */
    turbopackGc: true,
    /** `next dev` compiles a client `import()` only when the browser first asks for its chunk. */
    turbopackLazyDynamicImports: true,
    /**
     * Adds a cookie-guarded bootstrap script to every page and the navigation lock to the client
     * bundle. It never ships: see `testingApi`.
     */
    exposeTestingApiInProductionBuild: testingApi,
  },
};

/**
 * Plugins are named as strings, not imported functions: Turbopack hands loader options
 * to Rust, so a function reference cannot cross that boundary. The same string list is
 * resolved by the webpack loader, so `next dev --turbopack` and `next build` compile MDX
 * through one configuration.
 *
 * - `remark-frontmatter` claims the `---` block, so it is metadata for the build to read
 *   (the lede — see `scripts/lib/page-source.ts`) rather than rendered prose.
 * - `remark-gfm` keeps tables, strikethrough and autolinks available to page authors.
 */
const withMdx = createMdx({
  options: {
    remarkPlugins: ["remark-frontmatter", "remark-gfm"],
  },
});

export default withMdx(nextConfig);
